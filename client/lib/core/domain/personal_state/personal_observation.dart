// ==============================================================================
// Nutrient Earth — Canonical Personal Observation Contract
// The single source of truth for raw and source-derived personal observations.
// Enforces temporal provenance (observed_at vs recorded_at) and non-elevation rules.
// ==============================================================================

import 'package:uuid/uuid.dart';
import 'user_consent.dart';

enum ObservationProvenance {
  observed('observed', 'Directly measured by authorized device or reported by user'),
  derived('derived', 'Calculated deterministically using verified computational rules'),
  inferred('inferred', 'Hypothesis generated by intelligence reasoning'),
  unknown('unknown', 'Information not currently available or verifiable');

  final String value;
  final String label;

  const ObservationProvenance(this.value, this.label);

  static ObservationProvenance fromString(String val) {
    return ObservationProvenance.values.firstWhere(
      (p) => p.value == val,
      orElse: () => ObservationProvenance.observed,
    );
  }
}

enum ObservationQualityStatus {
  validated('validated', 'Verified against schema and range checks'),
  provisional('provisional', 'Awaiting cross-source reconciliation'),
  suspect('suspect', 'Identified as potential outlier or conflicting reading'),
  corrected('corrected', 'Superseded by user correction or updated provider record'),
  deleted('deleted', 'Soft-deleted by user or provider revocation');

  final String value;
  final String label;

  const ObservationQualityStatus(this.value, this.label);

  static ObservationQualityStatus fromString(String val) {
    return ObservationQualityStatus.values.firstWhere(
      (q) => q.value == val,
      orElse: () => ObservationQualityStatus.validated,
    );
  }
}

enum ObservationSourceProvider {
  androidHealthConnect('android_health_connect', 'Android Health Connect'),
  appleHealthKit('apple_healthkit', 'Apple HealthKit'),
  openMeteo('open_meteo', 'Open-Meteo Environmental Telemetry'),
  userInput('user_input', 'Direct User Interaction & Logging'),
  deviceSensor('device_sensor', 'Authorized Device Local Sensor'),
  clinicalLab('clinical_lab', 'Validated Clinical Diagnostic Laboratory'),
  aiPipeline('ai_pipeline', 'Nutrient Earth AI Intelligence Engine');

  final String value;
  final String label;

  const ObservationSourceProvider(this.value, this.label);

  static ObservationSourceProvider fromString(String val) {
    return ObservationSourceProvider.values.firstWhere(
      (s) => s.value == val,
      orElse: () => ObservationSourceProvider.userInput,
    );
  }
}

class PersonalObservation {
  final String id;
  final String userId;
  final String observationType;
  final double? numericValue;
  final String? textValue;
  final Map<String, dynamic> structuredPayload;
  final String? unit;
  final ObservationSourceProvider sourceProvider;
  final String? deviceModel;
  final String? externalRecordId;
  final String? idempotencyKey;
  final DateTime observedAt;
  final DateTime recordedAt;
  final String timezone;
  final ObservationQualityStatus qualityStatus;
  final ObservationProvenance provenanceType;
  final ConsentScope consentScope;
  final int schemaVersion;

  PersonalObservation({
    required this.id,
    required this.userId,
    required this.observationType,
    this.numericValue,
    this.textValue,
    this.structuredPayload = const {},
    this.unit,
    required this.sourceProvider,
    this.deviceModel,
    this.externalRecordId,
    this.idempotencyKey,
    required this.observedAt,
    required this.recordedAt,
    this.timezone = 'UTC',
    this.qualityStatus = ObservationQualityStatus.validated,
    required this.provenanceType,
    this.consentScope = ConsentScope.healthRead,
    this.schemaVersion = 1,
  }) {
    // Non-Elevation Rule Enforcement:
    // AI Pipeline output can NEVER be classified as directly observed.
    if (sourceProvider == ObservationSourceProvider.aiPipeline &&
        provenanceType == ObservationProvenance.observed) {
      throw ArgumentError(
        'Non-Elevation Violation: AI pipeline inferences can never be classified as observed.',
      );
    }
  }

  /// Create a direct verified observation from an authorized device or user input.
  factory PersonalObservation.observed({
    required String userId,
    required String observationType,
    double? numericValue,
    String? textValue,
    Map<String, dynamic> structuredPayload = const {},
    String? unit,
    required ObservationSourceProvider sourceProvider,
    String? deviceModel,
    String? externalRecordId,
    String? idempotencyKey,
    required DateTime observedAt,
    String timezone = 'UTC',
    ConsentScope consentScope = ConsentScope.healthRead,
  }) {
    if (sourceProvider == ObservationSourceProvider.aiPipeline) {
      throw ArgumentError('AI Pipeline cannot create direct observations.');
    }

    return PersonalObservation(
      id: const Uuid().v4(),
      userId: userId,
      observationType: observationType,
      numericValue: numericValue,
      textValue: textValue,
      structuredPayload: structuredPayload,
      unit: unit,
      sourceProvider: sourceProvider,
      deviceModel: deviceModel,
      externalRecordId: externalRecordId,
      idempotencyKey: idempotencyKey,
      observedAt: observedAt.toUtc(),
      recordedAt: DateTime.now().toUtc(),
      timezone: timezone,
      qualityStatus: ObservationQualityStatus.validated,
      provenanceType: ObservationProvenance.observed,
      consentScope: consentScope,
    );
  }

  /// Create a derived observation calculated from verified computational formulas.
  factory PersonalObservation.derived({
    required String userId,
    required String observationType,
    required double numericValue,
    String? unit,
    Map<String, dynamic> computationalProvenance = const {},
    required DateTime observedAt,
    String timezone = 'UTC',
    ConsentScope consentScope = ConsentScope.aiPersonalization,
  }) {
    return PersonalObservation(
      id: const Uuid().v4(),
      userId: userId,
      observationType: observationType,
      numericValue: numericValue,
      structuredPayload: computationalProvenance,
      unit: unit,
      sourceProvider: ObservationSourceProvider.aiPipeline,
      observedAt: observedAt.toUtc(),
      recordedAt: DateTime.now().toUtc(),
      timezone: timezone,
      qualityStatus: ObservationQualityStatus.validated,
      provenanceType: ObservationProvenance.derived,
      consentScope: consentScope,
    );
  }

  /// Create an AI-inferred hypothesis or context interpretation.
  factory PersonalObservation.inferred({
    required String userId,
    required String observationType,
    double? confidenceScore,
    String? explanation,
    Map<String, dynamic> inferenceContext = const {},
    required DateTime observedAt,
    String timezone = 'UTC',
    ConsentScope consentScope = ConsentScope.aiPersonalization,
  }) {
    return PersonalObservation(
      id: const Uuid().v4(),
      userId: userId,
      observationType: observationType,
      numericValue: confidenceScore,
      textValue: explanation,
      structuredPayload: inferenceContext,
      sourceProvider: ObservationSourceProvider.aiPipeline,
      observedAt: observedAt.toUtc(),
      recordedAt: DateTime.now().toUtc(),
      timezone: timezone,
      qualityStatus: ObservationQualityStatus.provisional,
      provenanceType: ObservationProvenance.inferred,
      consentScope: consentScope,
    );
  }

  bool get isDirectObservation => provenanceType == ObservationProvenance.observed;
  bool get isDerived => provenanceType == ObservationProvenance.derived;
  bool get isInferred => provenanceType == ObservationProvenance.inferred;

  factory PersonalObservation.fromJson(Map<String, dynamic> json) {
    return PersonalObservation(
      id: json['id'] as String? ?? const Uuid().v4(),
      userId: json['user_id'] as String? ?? '',
      observationType: json['observation_type'] as String? ?? '',
      numericValue: json['numeric_value'] != null
          ? (json['numeric_value'] as num).toDouble()
          : null,
      textValue: json['text_value'] as String?,
      structuredPayload: json['structured_payload'] is Map<String, dynamic>
          ? json['structured_payload'] as Map<String, dynamic>
          : const {},
      unit: json['unit'] as String?,
      sourceProvider: ObservationSourceProvider.fromString(
        json['source_provider'] as String? ?? '',
      ),
      deviceModel: json['device_model'] as String?,
      externalRecordId: json['external_record_id'] as String?,
      idempotencyKey: json['idempotency_key'] as String?,
      observedAt: DateTime.tryParse(json['observed_at'] as String? ?? '') ??
          DateTime.now().toUtc(),
      recordedAt: DateTime.tryParse(json['recorded_at'] as String? ?? '') ??
          DateTime.now().toUtc(),
      timezone: json['timezone'] as String? ?? 'UTC',
      qualityStatus: ObservationQualityStatus.fromString(
        json['quality_status'] as String? ?? '',
      ),
      provenanceType: ObservationProvenance.fromString(
        json['provenance_type'] as String? ?? '',
      ),
      consentScope: ConsentScope.fromString(
        json['consent_scope'] as String? ?? '',
      ),
      schemaVersion: json['schema_version'] as int? ?? 1,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'user_id': userId,
      'observation_type': observationType,
      if (numericValue != null) 'numeric_value': numericValue,
      if (textValue != null) 'text_value': textValue,
      'structured_payload': structuredPayload,
      if (unit != null) 'unit': unit,
      'source_provider': sourceProvider.value,
      if (deviceModel != null) 'device_model': deviceModel,
      if (externalRecordId != null) 'external_record_id': externalRecordId,
      if (idempotencyKey != null) 'idempotency_key': idempotencyKey,
      'observed_at': observedAt.toIso8601String(),
      'recorded_at': recordedAt.toIso8601String(),
      'timezone': timezone,
      'quality_status': qualityStatus.value,
      'provenance_type': provenanceType.value,
      'consent_scope': consentScope.value,
      'schema_version': schemaVersion,
    };
  }
}
